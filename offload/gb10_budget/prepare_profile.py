"""Emit an experiment-only profiler config; never connect to a host or launch a service."""
from __future__ import annotations

import argparse
import json
import shlex
from pathlib import Path


def render(base: str, iterations: int) -> str:
    if iterations < 1 or iterations > 32:
        raise ValueError("Choose 1..32 iterations to bound profiling memory")
    cfg = {"profiler": "torch", "torch_profiler_dir": "/opt/dsv41-sp1-profile",
           "torch_profiler_activities": ["CPU", "CUDA"], "torch_profiler_with_stack": False,
           "torch_profiler_with_flops": False, "torch_profiler_record_shapes": False,
           "torch_profiler_with_memory": False, "torch_profiler_use_gzip": True,
           "torch_profiler_dump_cuda_time_total": True, "ignore_frontend": True,
           "detailed_trace_annotation": True, "max_iterations": iterations}
    extra = shlex.quote(" --profiler-config " + shlex.quote(json.dumps(cfg, separators=(",", ":"))))
    return ("# Generated by SP1; coordinator only, in a reserved experiment window.\n"
            f". {shlex.quote(base)}\n"
            "LABEL=SP1-profile\n"
            f"EXP_EXTRA_ARGS=\"${{EXP_EXTRA_ARGS:-}}\"{extra}\n"
            'EXTRA_DOCKER_ARGS="${EXTRA_DOCKER_ARGS:-} -v \\$HOME/dsv41-offload-run/sp1-profile:/opt/dsv41-sp1-profile"\n')


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--base", required=True, type=Path, help="Reviewed experiment .env in the current checkout")
    ap.add_argument("--output", required=True, type=Path, help="Fresh path, preferably /tmp/SP1-profile.env")
    ap.add_argument("--iterations", type=int, default=16)
    args = ap.parse_args()
    if not args.base.is_file():
        ap.error(f"Missing reviewed base: {args.base}")
    # Do not emit an accidentally deployable incomplete/foreign config.
    if "offload/launch/configs" not in str(args.base):
        ap.error("Base must be an existing offload/launch/configs experiment")
    content = render(str(args.base), args.iterations)
    with args.output.open("x") as target:
        target.write(content)
    print(f"Prepared {args.output}; no service or network operation performed")


if __name__ == "__main__":
    main()
